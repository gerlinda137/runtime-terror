const fs = require('fs');
const path = require('path');

const iconDir = path.join(__dirname, '../node_modules/cryptocurrency-icons/svg/color');

const outputPath = path.join(
  __dirname,
  '../src/app/shared/directive/market-display/crypto-icon-manifest.ts',
);

const symbols = fs
  .readdirSync(iconDir)
  .filter((f) => f.endsWith('.svg'))
  .map((f) => f.replace('.svg', ''));

const fileContent = `// Auto-generated by scripts/generate-crypto-icon-manifest.js — do not edit by hand.
export const CRYPTO_ICON_SYMBOLS = new Set<string>(${JSON.stringify(symbols)});
`;

fs.writeFileSync(outputPath,fileContent);

console.log(`Generated ${symbols.length} icon symbols to ${outputPath}`);